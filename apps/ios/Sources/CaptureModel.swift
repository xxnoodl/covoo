import AVFoundation
import SwiftUI
import UIKit

@MainActor
final class CaptureModel: ObservableObject {
    @Published var state = CaptureState()
    @Published var requesting = false
    @Published var streamState = StreamState()
    @Published var pairingLink = ""
    @Published var packetProtection = true
    @Published var keepRecordingOnPhone = false
    @Published var lowLatency = false
    @Published var localMonitor = false
    @Published var monitorGain: Float = 0.2
    @Published var monitorMuted = false
    private var streamer: AudioStreamer?
    private let pairingStore = PairingStore()
    private let service = CaptureService()
    private var observers: [NSObjectProtocol] = []
    private var backgroundFinalizationTask: UIBackgroundTaskIdentifier = .invalid

    init() {
        do {
            if let saved = try pairingStore.load() {
                pairingLink = saved
                streamState.status = "Saved pairing loaded. Tap Connect. If the receiver address changed or pairing was revoked, scan again."
            }
        } catch { streamState.status = error.localizedDescription }
        observe(AVAudioSession.interruptionNotification, message: "Audio interrupted. Start again when ready.")
        observe(AVAudioSession.mediaServicesWereLostNotification, message: "Audio service lost. Start again when ready.")
        observe(AVAudioSession.mediaServicesWereResetNotification, message: "Audio service reset. Start again when ready.")
        // M1 records in the foreground. Background/lock support is a later acceptance test.
        observers.append(NotificationCenter.default.addObserver(forName: UIApplication.willResignActiveNotification,
            object: nil, queue: .main) { [weak self] _ in
                // Notification delivery is explicitly on main. Request the lease
                // before the transition, not in a later queued task.
                MainActor.assumeIsolated { self?.beginBackgroundFinalization() }
            })
        observers.append(NotificationCenter.default.addObserver(forName: UIApplication.didEnterBackgroundNotification,
            object: nil, queue: .main) { [weak self] _ in
                Task { @MainActor [weak self] in
                    guard let self else { return }
                    self.beginBackgroundFinalization()
                    self.service.stop(reason: "App backgrounded. Recording stopped.")
                    if !self.state.recording && !self.requesting { self.pauseIdleConnection() }
                }
            })
        observers.append(NotificationCenter.default.addObserver(forName: UIApplication.didBecomeActiveNotification,
            object: nil, queue: .main) { [weak self] _ in
                Task { @MainActor [weak self] in
                    self?.streamer?.resumeAfterBackground()
                    self?.endBackgroundFinalization()
                }
            })
        observers.append(NotificationCenter.default.addObserver(forName: AVAudioSession.routeChangeNotification,
            object: nil, queue: .main) { [weak self] notification in
                let reason = (notification.userInfo?[AVAudioSessionRouteChangeReasonKey] as? NSNumber)?.uintValue
                // Category changes are generated by our own session setup.
                if reason != AVAudioSession.RouteChangeReason.categoryChange.rawValue {
                    Task { @MainActor [weak self] in self?.service.routeChanged() }
                }
            })
    }

    private func beginBackgroundFinalization() {
        guard (state.recording || requesting), backgroundFinalizationTask == .invalid else { return }
        backgroundFinalizationTask = UIApplication.shared.beginBackgroundTask(withName: "Finish covoo recording") { [weak self] in
            self?.endBackgroundFinalization()
        }
    }

    private func endBackgroundFinalization() {
        guard backgroundFinalizationTask != .invalid else { return }
        let identifier = backgroundFinalizationTask
        backgroundFinalizationTask = .invalid
        UIApplication.shared.endBackgroundTask(identifier)
    }

    private func pauseIdleConnection() {
        guard let streamer else { endBackgroundFinalization(); return }
        streamer.pauseWhenIdle { [weak self] in
            Task { @MainActor in
                guard let self else { return }
                // Foreground can return while the network pause was queued.
                if UIApplication.shared.applicationState != .background {
                    self.streamer?.resumeAfterBackground()
                }
                self.endBackgroundFinalization()
            }
        }
    }

    private func observe(_ name: Notification.Name, message: String) {
        observers.append(NotificationCenter.default.addObserver(forName: name, object: nil, queue: .main) {
            [weak self] _ in
                Task { @MainActor [weak self] in self?.service.stop(reason: message) }
        })
    }

    func start(streamToPC: Bool = false) {
        guard !requesting, !state.recording else { return }
        requesting = true
        state.status = "Requesting microphone access"
        Task {
            guard await AVAudioApplication.requestRecordPermission() else {
                state.status = "Microphone access denied. Enable it in Settings > Privacy & Security > Microphone."
                requesting = false
                return
            }
            guard UIApplication.shared.applicationState != .background else {
                state.status = "Return to the app to start recording."
                requesting = false
                return
            }
            state.status = "Starting"
            service.start(streamer: streamToPC ? streamer : nil,
                keepLocal: !streamToPC || keepRecordingOnPhone, lowLatency: lowLatency,
                localMonitor: localMonitor, monitorGain: monitorGain, monitorMuted: monitorMuted) { [weak self] value in
                Task { @MainActor in
                    self?.state = value
                    self?.requesting = value.finalizing
                    if !value.recording && !value.finalizing,
                        UIApplication.shared.applicationState == .background {
                        self?.pauseIdleConnection()
                    }
                }
            }
        }
    }

    func stop() { service.stop() }

    func updateMonitorLevel() {
        service.setLocalMonitorLevel(gain: monitorGain, muted: monitorMuted)
    }

    func acceptPairingURL(_ url: URL) {
        guard !state.recording, !requesting else { return }
        do {
            _ = try PairingDetails(link: url.absoluteString)
            pairingLink = url.absoluteString
            streamState.status = "Pairing link received. Tap Connect."
        } catch { streamState.status = error.localizedDescription }
    }

    func connectReceiver() {
        guard !state.recording, !requesting else { return }
        do {
            let pairing = try PairingDetails(link: pairingLink)
            streamer?.disconnect()
            let transport = try AudioStreamer(pairing: pairing, packetProtection: packetProtection, lowLatency: lowLatency) { [weak self] value in
                Task { @MainActor in self?.streamState = value }
            }
            streamer = transport
            transport.connect()
        } catch { streamState.status = error.localizedDescription }
    }

    func disconnectReceiver() {
        guard !state.recording, !requesting else { return }
        streamer?.disconnect()
        streamer = nil
        streamState = StreamState()
    }

    func rememberReceiver() {
        guard !state.recording, !requesting else { return }
        do {
            try pairingStore.save(pairingLink)
            streamState.status = "Pairing remembered on this phone. Connect still checks the pinned certificate."
        } catch { streamState.status = error.localizedDescription }
    }

    func forgetReceiver() {
        guard !state.recording, !requesting else { return }
        do {
            try pairingStore.forget()
            disconnectReceiver()
            pairingLink = ""
            streamState.status = "Pairing forgotten on this phone. To revoke all phones, use Revoke saved pairing on Windows."
        } catch { streamState.status = error.localizedDescription }
    }

    deinit {
        for observer in observers { NotificationCenter.default.removeObserver(observer) }
        let identifier = backgroundFinalizationTask
        if identifier != .invalid {
            DispatchQueue.main.async { UIApplication.shared.endBackgroundTask(identifier) }
        }
    }
}
